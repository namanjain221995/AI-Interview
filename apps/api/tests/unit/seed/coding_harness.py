# Literal generation
# =============================================================================


def _json_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def _float_lit(value: float) -> str:
    text = repr(float(value))
    return text if any(c in text for c in ".eE") else text + ".0"


_JAVA_TYPES = {
    "int": "int", "long": "long", "float": "double", "bool": "boolean", "string": "String",
}  # fmt: skip
_CPP_TYPES = {
    "int": "int", "long": "long long", "float": "double", "bool": "bool", "string": "std::string",
}  # fmt: skip
_GO_TYPES = {"int": "int", "long": "int64", "float": "float64", "bool": "bool", "string": "string"}


def java_type(type_name: str) -> str:
    if is_array_type(type_name):
        return java_type(element_type(type_name)) + "[]"
    return _JAVA_TYPES[type_name]


def cpp_type(type_name: str) -> str:
    if is_array_type(type_name):
        return f"std::vector<{cpp_type(element_type(type_name))}>"
    return _CPP_TYPES[type_name]


def go_type(type_name: str) -> str:
    if is_array_type(type_name):
        return "[]" + go_type(element_type(type_name))
    return _GO_TYPES[type_name]


def java_literal(value: Any, type_name: str, *, nested: bool = False) -> str:
    if is_array_type(type_name):
        inner = ",".join(java_literal(v, element_type(type_name), nested=True) for v in value)
        return ("{" + inner + "}") if nested else f"new {java_type(type_name)}{{{inner}}}"
    if type_name == "int":
        return str(value)
    if type_name == "long":
        return f"{value}L"
    if type_name == "float":
        return _float_lit(value)
    if type_name == "bool":
        return "true" if value else "false"
    return _json_str(value)


def cpp_literal(value: Any, type_name: str) -> str:
    if is_array_type(type_name):
        inner = ",".join(cpp_literal(v, element_type(type_name)) for v in value)
        return f"{cpp_type(type_name)}{{{inner}}}"
    if type_name == "int":
        return str(value)
    if type_name == "long":
        return f"{value}LL"
    if type_name == "float":
        return _float_lit(value)
    if type_name == "bool":
        return "true" if value else "false"
    return f"std::string({_json_str(value)})"


def go_literal(value: Any, type_name: str, *, nested: bool = False) -> str:
    if is_array_type(type_name):
        inner = ",".join(go_literal(v, element_type(type_name), nested=True) for v in value)
        return ("{" + inner + "}") if nested else f"{go_type(type_name)}{{{inner}}}"
    if type_name == "int":
        return str(value)
    if type_name == "long":
        return str(value) if nested else f"int64({value})"
    if type_name == "float":
        return _float_lit(value)
    if type_name == "bool":
        return "true" if value else "false"
    return _json_str(value)


