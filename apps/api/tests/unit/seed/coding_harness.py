REPO_ROOT = Path(__file__).resolve().parents[5]
WEB_BIN = REPO_ROOT / "apps" / "web" / "node_modules" / ".bin"
RUN_TIMEOUT_S = 60


@dataclass(slots=True)
class CaseOutcome:
    test_id: str
    ok: bool
    value: Any = None
    error: str | None = None


@dataclass(slots=True)
class Program:
    """Generated sources plus the shell steps that build and run them."""

    language: CodeLanguage
    files: dict[str, str]
    build: list[list[str]] = field(default_factory=list)
    run: list[str] = field(default_factory=list)


class ToolchainMissing(RuntimeError):
    pass


