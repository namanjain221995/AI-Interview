def _which(name: str) -> str | None:
    return shutil.which(name)


def toolchain_status(language: CodeLanguage) -> tuple[bool, str]:
    """(available, reason) for running ``language`` locally."""
    if language in (CodeLanguage.PYTHON, CodeLanguage.SQL):
        return True, "in-process"
    if language == CodeLanguage.JAVASCRIPT:
        return (bool(_which("node")), "node")
    if language == CodeLanguage.TYPESCRIPT:
        ok = bool(_which("node")) and (WEB_BIN / "esbuild").exists() and (WEB_BIN / "tsc").exists()
        return ok, "node + apps/web tsc/esbuild"
    if language == CodeLanguage.CPP:
        return (bool(_which("g++")), "g++")
    if language == CodeLanguage.JAVA:
        return (bool(_which("javac")) and bool(_which("java")), "javac + java")
    if language == CodeLanguage.GO:
        return (bool(_which("go")), "go")
    return False, "unsupported"


