def _run(cmd: list[str], cwd: Path, *, timeout: int = RUN_TIMEOUT_S) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=timeout, check=False)  # noqa: S603


def _typescript_build(workdir: Path) -> None:
    proc = _run(
        [
            str(WEB_BIN / "esbuild"),
            "main.ts",
            "--format=cjs",
            "--platform=node",
            "--log-level=error",
            "--outfile=main.js",
        ],
        workdir,
    )
    if proc.returncode != 0:
        raise AssertionError(f"esbuild failed:\n{proc.stderr}")


def typecheck_typescript(sources: dict[str, str]) -> str:
    """Strict ``tsc --noEmit`` over many TS modules at once; returns diagnostics ('' when clean)."""
    with tempfile.TemporaryDirectory(prefix="ts-check-") as tmp:
        root = Path(tmp)
        for name, text in sources.items():
            (root / name).write_text(text, encoding="utf-8")
        (root / "tsconfig.json").write_text(
            json.dumps(
                {
                    "compilerOptions": {
                        "strict": True,
                        "noEmit": True,
                        "target": "ES2022",
                        "lib": ["ES2022", "DOM"],
                        "module": "ESNext",
                        "moduleResolution": "Bundler",
                        "types": [],
                        "skipLibCheck": True,
                        "noFallthroughCasesInSwitch": True,
                    },
                    "include": ["*.ts"],
                }
            ),
            encoding="utf-8",
        )
        proc = _run([str(WEB_BIN / "tsc"), "-p", "tsconfig.json"], root, timeout=180)
        return "" if proc.returncode == 0 else (proc.stdout + proc.stderr)


def transpile_typescript(sources: dict[str, str]) -> dict[str, str]:
    """Strip the types of many TypeScript sources with one ``esbuild`` call
    (transform only, no bundling: top-level declarations stay top level)."""
    if not sources:
        return {}
    with tempfile.TemporaryDirectory(prefix="ts-transpile-") as tmp:
        root = Path(tmp)
        names = []
        for name, text in sources.items():
            (root / f"{name}.ts").write_text(text, encoding="utf-8")
            names.append(f"{name}.ts")
        proc = _run(
            [str(WEB_BIN / "esbuild"), *names, "--outdir=out", "--log-level=error"], root, timeout=300
        )
        if proc.returncode != 0:
            raise AssertionError(f"esbuild failed:\n{proc.stderr[-4000:]}")
        return {name: (root / "out" / f"{name}.js").read_text(encoding="utf-8") for name in sources}


def run_typescript(problems: Sequence[CodingQuestionSeed]) -> RunReport:
    """Explicit TypeScript references and starters, transpiled in one batch and
    executed by the batched node runner (messages say ``typescript``)."""
    sources: dict[str, str] = {}
    for problem in problems:
        if CodeLanguage.TYPESCRIPT in problem.reference_solutions:
            sources[f"{problem.slug}__reference"] = problem.reference_solutions[CodeLanguage.TYPESCRIPT]
        if CodeLanguage.TYPESCRIPT in problem.explicit_starter_code:
            sources[f"{problem.slug}__starter"] = problem.starter_code[CodeLanguage.TYPESCRIPT]
    compiled = transpile_typescript(sources)
    variants = []
    for problem in problems:
        reference = compiled.get(f"{problem.slug}__reference")
        starter = compiled.get(f"{problem.slug}__starter")
        if reference is None and starter is None:
            continue
        variants.append(
            problem.model_copy(
                update={
                    "reference_solutions": {CodeLanguage.JAVASCRIPT: reference} if reference else {},
                    "starter_code": {CodeLanguage.JAVASCRIPT: starter} if starter else {},
                }
            )
        )
    report = run_function_problems(variants, languages=[CodeLanguage.JAVASCRIPT])
    for messages in (*report.errors.values(), *report.warnings.values()):
        messages[:] = [m.replace("[javascript ", "[typescript ") for m in messages]
    return report


def run_python(problem: CodingQuestionSeed, code: str) -> list[CaseOutcome]:
    sig = problem.signature
    assert sig is not None
    namespace: dict[str, Any] = {"__name__": f"solution_{problem.slug}"}
    exec(compile(code, f"<{problem.slug}.py>", "exec"), namespace)  # noqa: S102 - curated reference code
    fn: Callable[..., Any] = namespace[sig.function_name]
    outcomes = []
    for test in problem.tests:
        try:
            value = fn(*copy.deepcopy(test.args or []))
            outcomes.append(CaseOutcome(test.id, True, json.loads(json.dumps(value))))
        except Exception as exc:  # noqa: BLE001 - reported per test
            outcomes.append(CaseOutcome(test.id, False, error=repr(exc)))
    return outcomes


def run_local(problem: CodingQuestionSeed, language: CodeLanguage, code: str) -> list[CaseOutcome]:
    """Execute ``code`` for every test with the local toolchain."""
    if language == CodeLanguage.PYTHON:
        return run_python(problem, code)
    available, reason = toolchain_status(language)
    if not available:
        raise ToolchainMissing(f"{language.value}: {reason} not installed")
    program = build_program(problem, language, code)
    with tempfile.TemporaryDirectory(prefix=f"harness-{problem.slug}-{language.value}-") as tmp:
        workdir = Path(tmp)
        for name, text in program.files.items():
            (workdir / name).write_text(text, encoding="utf-8")
        if language == CodeLanguage.TYPESCRIPT:
            _typescript_build(workdir)
        for step in program.build:
            proc = _run(step, workdir, timeout=180)
            if proc.returncode != 0:
                raise AssertionError(f"{language.value} build failed:\n{proc.stdout}\n{proc.stderr}")
        proc = _run(program.run, workdir)
        if proc.returncode != 0:
            raise AssertionError(
                f"{language.value} run failed ({proc.returncode}):\n{proc.stdout[-2000:]}\n{proc.stderr[-4000:]}"
            )
        return decode_output(problem, proc.stdout)


def mismatches(problem: CodingQuestionSeed, outcomes: Sequence[CaseOutcome]) -> list[str]:
    """Human-readable failures of ``outcomes`` against the expected values."""
    sig = problem.signature
    assert sig is not None
    problems = []
    for test, outcome in zip(problem.tests, outcomes, strict=True):
        if not outcome.ok:
            problems.append(f"{test.id}: error {outcome.error}")
        elif not compare_results(
            outcome.value,
            test.expected,
            return_type=sig.return_type,
            comparison=sig.comparison,
            tolerance=sig.tolerance,
        ):
            shown = json.dumps(outcome.value)
            problems.append(f"{test.id}: got {shown[:200]} expected {json.dumps(test.expected)[:200]}")
    return problems


