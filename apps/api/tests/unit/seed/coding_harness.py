def _tests_json(tests: Sequence[CodingTestSeed]) -> str:
    return json.dumps([t.args for t in tests], separators=(",", ":"))


def _js_driver(entry: str, tests: Sequence[CodingTestSeed], *, typed: bool) -> str:
    fn_cast = f"({entry} as unknown as (...a: unknown[]) => unknown)" if typed else entry
    decl = "const __tests: unknown[][] = " if typed else "const __tests = "
    out_decl = "const __out: unknown[] = [];" if typed else "const __out = [];"
    err = "(e: unknown)" if typed else "(e)"
    return f"""
;(() => {{
  {decl}{_tests_json(tests)};
  {out_decl}
  for (const __args of __tests) {{
    try {{
      const __r = {fn_cast}(...__args);
      __out.push({{ ok: true, value: __r === undefined ? null : __r }});
    }} catch {err} {{
      __out.push({{ ok: false, error: String(e) }});
    }}
  }}
  console.log(JSON.stringify(__out));
}})();
"""


_JAVA_JSON_HELPERS = r"""
  static String q(String s) {
    if (s == null) return "null";
    StringBuilder b = new StringBuilder("\"");
    for (int i = 0; i < s.length(); i++) {
      char c = s.charAt(i);
      if (c == '"' || c == '\\') { b.append('\\').append(c); }
      else if (c < 0x20) { b.append(String.format("\\u%04x", (int) c)); }
      else { b.append(c); }
    }
    return b.append('"').toString();
  }
  static String j(int v) { return Integer.toString(v); }
  static String j(long v) { return Long.toString(v); }
  static String j(double v) { return (Double.isNaN(v) || Double.isInfinite(v)) ? "null" : Double.toString(v); }
  static String j(boolean v) { return v ? "true" : "false"; }
  static String j(String v) { return q(v); }
  static String j(int[] v) { if (v == null) return "null"; StringBuilder b = new StringBuilder("["); for (int i = 0; i < v.length; i++) { if (i > 0) b.append(','); b.append(j(v[i])); } return b.append(']').toString(); }
  static String j(long[] v) { if (v == null) return "null"; StringBuilder b = new StringBuilder("["); for (int i = 0; i < v.length; i++) { if (i > 0) b.append(','); b.append(j(v[i])); } return b.append(']').toString(); }
  static String j(double[] v) { if (v == null) return "null"; StringBuilder b = new StringBuilder("["); for (int i = 0; i < v.length; i++) { if (i > 0) b.append(','); b.append(j(v[i])); } return b.append(']').toString(); }
  static String j(boolean[] v) { if (v == null) return "null"; StringBuilder b = new StringBuilder("["); for (int i = 0; i < v.length; i++) { if (i > 0) b.append(','); b.append(j(v[i])); } return b.append(']').toString(); }
  static String j(String[] v) { if (v == null) return "null"; StringBuilder b = new StringBuilder("["); for (int i = 0; i < v.length; i++) { if (i > 0) b.append(','); b.append(j(v[i])); } return b.append(']').toString(); }
  static String j(int[][] v) { if (v == null) return "null"; StringBuilder b = new StringBuilder("["); for (int i = 0; i < v.length; i++) { if (i > 0) b.append(','); b.append(j(v[i])); } return b.append(']').toString(); }
  static String j(String[][] v) { if (v == null) return "null"; StringBuilder b = new StringBuilder("["); for (int i = 0; i < v.length; i++) { if (i > 0) b.append(','); b.append(j(v[i])); } return b.append(']').toString(); }
"""


def _java_driver(problem: CodingQuestionSeed, tests: Sequence[CodingTestSeed]) -> str:
    sig = problem.signature
    assert sig is not None
    entry = entry_point_name(sig.function_name, CodeLanguage.JAVA)
    ret = java_type(sig.return_type)
    methods = []
    for index, test in enumerate(tests):
        assert test.args is not None
        decls = "\n".join(
            f"    {java_type(p.type)} a{i} = {java_literal(arg, p.type)};"
            for i, (p, arg) in enumerate(zip(sig.params, test.args, strict=True))
        )
        call_args = ", ".join(f"a{i}" for i in range(len(sig.params)))
        methods.append(
            f"""  static String t{index}() {{
    try {{
{decls}
    {ret} r = new Solution().{entry}({call_args});
    return "{{\\"ok\\":true,\\"value\\":" + j(r) + "}}";
    }} catch (Throwable e) {{
      return "{{\\"ok\\":false,\\"error\\":" + q(e.toString()) + "}}";
    }}
  }}"""
        )
    calls = "\n".join(
        "    out.append(t0());" if i == 0 else f'    out.append(",").append(t{i}());'
        for i in range(len(tests))
    )
    return f"""import java.util.*;

public class Main {{
{_JAVA_JSON_HELPERS}
{chr(10).join(methods)}
  public static void main(String[] args) {{
    StringBuilder out = new StringBuilder("[");
{calls}
    out.append("]");
    System.out.println(out);
  }}
}}
"""


_CPP_JSON_HELPERS = r"""
static std::string harness_q(const std::string& s) {
  std::string out = "\"";
  for (unsigned char c : s) {
    if (c == '"' || c == '\\') { out += '\\'; out += static_cast<char>(c); }
    else if (c < 0x20) { char buf[8]; std::snprintf(buf, sizeof buf, "\\u%04x", c); out += buf; }
    else { out += static_cast<char>(c); }
  }
  return out + "\"";
}
static std::string harness_j(int v) { return std::to_string(v); }
static std::string harness_j(long v) { return std::to_string(v); }
static std::string harness_j(long long v) { return std::to_string(v); }
static std::string harness_j(double v) {
  if (std::isnan(v) || std::isinf(v)) return "null";
  char buf[64]; std::snprintf(buf, sizeof buf, "%.17g", v); return buf;
}
static std::string harness_j(bool v) { return v ? "true" : "false"; }
static std::string harness_j(const std::string& v) { return harness_q(v); }
template <typename T> static std::string harness_j(const std::vector<T>& v) {
  std::string out = "[";
  for (std::size_t i = 0; i < v.size(); ++i) { if (i) out += ","; T x = v[i]; out += harness_j(x); }
  return out + "]";
}
"""


def _cpp_driver(problem: CodingQuestionSeed, tests: Sequence[CodingTestSeed]) -> str:
    sig = problem.signature
    assert sig is not None
    entry = entry_point_name(sig.function_name, CodeLanguage.CPP)
    blocks = []
    for index, test in enumerate(tests):
        assert test.args is not None
        decls = " ".join(
            f"{cpp_type(p.type)} a{i} = {cpp_literal(arg, p.type)};"
            for i, (p, arg) in enumerate(zip(sig.params, test.args, strict=True))
        )
        call_args = ", ".join(f"a{i}" for i in range(len(sig.params)))
        sep = "" if index == 0 else 'out += ",";'
        blocks.append(
            f"""  {sep} try {{ {decls} Solution s; {cpp_type(sig.return_type)} r = s.{entry}({call_args});
    out += "{{\\"ok\\":true,\\"value\\":" + harness_j(r) + "}}"; }}
  catch (const std::exception& e) {{ out += "{{\\"ok\\":false,\\"error\\":" + harness_q(e.what()) + "}}"; }}"""
        )
    return f"""
// ---- harness ----
#include <cmath>
#include <cstdio>
#include <iostream>
#include <stdexcept>
#include <string>
#include <vector>
{_CPP_JSON_HELPERS}
int main() {{
  std::string out = "[";
{chr(10).join(blocks)}
  out += "]";
  std::cout << out << std::endl;
  return 0;
}}
"""


def _go_driver(problem: CodingQuestionSeed, tests: Sequence[CodingTestSeed]) -> str:
    sig = problem.signature
    assert sig is not None
    entry = entry_point_name(sig.function_name, CodeLanguage.GO)
    calls = []
    for test in tests:
        assert test.args is not None
        args = ", ".join(go_literal(arg, p.type) for p, arg in zip(sig.params, test.args, strict=True))
        calls.append(f"\tout = append(out, __run(func() any {{ return {entry}({args}) }}))")
    return f"""package main

import (
\t"encoding/json"
\t"fmt"
\t"os"
)

func __run(f func() any) (res map[string]any) {{
\tdefer func() {{
\t\tif r := recover(); r != nil {{
\t\t\tres = map[string]any{{"ok": false, "error": fmt.Sprint(r)}}
\t\t}}
\t}}()
\treturn map[string]any{{"ok": true, "value": f()}}
}}

func main() {{
\tout := []map[string]any{{}}
{chr(10).join(calls)}
\tb, err := json.Marshal(out)
\tif err != nil {{
\t\tfmt.Fprintln(os.Stderr, err)
\t\tos.Exit(2)
\t}}
\tos.Stdout.Write(b)
}}
"""


def build_program(problem: CodingQuestionSeed, language: CodeLanguage, code: str) -> Program:
    """Sources + build/run steps for ``code`` against every test of ``problem``."""
    sig = problem.signature
    if sig is None:
        raise ValueError("build_program handles function problems only")
    tests = problem.tests
    entry = entry_point_name(sig.function_name, language)
    if language == CodeLanguage.JAVASCRIPT:
        return Program(language, {"main.js": '"use strict";\n' + code + _js_driver(entry, tests, typed=False)},
                       run=["node", "main.js"])  # fmt: skip
    if language == CodeLanguage.TYPESCRIPT:
        source = code + _js_driver(entry, tests, typed=True) + "\nexport {};\n"
        return Program(language, {"main.ts": source}, run=["node", "main.js"])
    if language == CodeLanguage.JAVA:
        return Program(
            language,
            {"Solution.java": code, "Main.java": _java_driver(problem, tests)},
            build=[["javac", "-nowarn", "-encoding", "UTF-8", "Solution.java", "Main.java"]],
            run=["java", "-Xss64m", "Main"],
        )
    if language == CodeLanguage.CPP:
        return Program(
            language,
            {"main.cpp": code + "\n" + _cpp_driver(problem, tests)},
            build=[["g++", "-std=c++17", "-O1", "-o", "main", "main.cpp"]],
            run=["./main"],
        )
    if language == CodeLanguage.GO:
        return Program(
            language,
            {
                "solution.go": code,
                "driver.go": _go_driver(problem, tests),
                "go.mod": "module harness\n\ngo 1.21\n",
            },
            build=[["go", "build", "-o", "main", "."]],
            run=["./main"],
        )
    raise ValueError(f"no generated driver for {language}")


def decode_output(problem: CodingQuestionSeed, stdout: str) -> list[CaseOutcome]:
    line = stdout.strip().splitlines()[-1] if stdout.strip() else "[]"
    records = json.loads(line)
    if len(records) != len(problem.tests):
        raise AssertionError(f"driver returned {len(records)} results for {len(problem.tests)} tests")
    return [
        CaseOutcome(test.id, bool(rec.get("ok")), rec.get("value"), rec.get("error"))
        for test, rec in zip(problem.tests, records, strict=True)
    ]


