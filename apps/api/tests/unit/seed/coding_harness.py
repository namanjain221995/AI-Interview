def run_sql_sqlite(
    problem: CodingQuestionSeed, query: str
) -> list[tuple[str, list[list[Any]] | None, str | None]]:
    """Run ``query`` once per test on a fresh in-memory SQLite database.
    Returns (test_id, rows, error)."""
    results: list[tuple[str, list[list[Any]] | None, str | None]] = []
    for test in problem.tests:
        conn = sqlite3.connect(":memory:")
        try:
            conn.executescript(problem.sql_setup or "")
            if test.setup_sql:
                conn.executescript(test.setup_sql)
            rows = [list(r) for r in conn.execute(query).fetchall()]
            results.append((test.id, rows, None))
        except sqlite3.Error as exc:
            results.append((test.id, None, str(exc)))
        finally:
            conn.close()
    return results


def sql_mismatches(problem: CodingQuestionSeed, results: Sequence[tuple[str, Any, str | None]]) -> list[str]:
    out = []
    for test, (test_id, rows, error) in zip(problem.tests, results, strict=True):
        assert test.id == test_id
        if error is not None:
            out.append(f"{test_id}: error {error}")
        elif not compare_sql_rows(rows, test.expected_rows or [], ordered=test.ordered):
            out.append(f"{test_id}: got {rows} expected {test.expected_rows}")
    return out


def is_number(value: Any) -> bool:
    return isinstance(value, int | float) and not isinstance(value, bool) and math.isfinite(value)
