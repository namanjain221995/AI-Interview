"""Multi-language verification harness for the curated coding problems.

Python and JavaScript are verified by the validator's batched runner
(:mod:`app.seed.runner`); this harness covers the other local toolchains.
TypeScript is transpiled for all problems with one ``esbuild`` call and then
runs through the same batched node runner (:func:`run_typescript`).

Generates a small driver per language that calls the candidate entry point
(:func:`app.seed.loaders.entry_point_name`) with each test's positional
arguments, prints one JSON array of ``{"ok": true, "value": ...}`` /
``{"ok": false, "error": "..."}`` records, and compares the decoded values
with :func:`app.seed.loaders.compare_results` — the same semantics the sandbox
harnesses implement. Python runs in-process; the other languages run with the
local toolchain when it is installed (``node``, the web app's ``tsc`` and
``esbuild``, ``g++``, ``javac``/``java``, ``go``). SQL problems run on SQLite.

The sources are generated by :func:`build_program` independently of where
they run, so the same files can be compiled in a container when a toolchain
is missing on the host.
"""

