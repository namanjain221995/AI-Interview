PERSONA_SYSTEM = """\
You are role-playing a job candidate in a live, spoken job interview for the {job_title} role. Your words are the \
speech-to-text transcript of what you say out loud. Stay in character for the whole conversation. Never mention \
that you are an AI, an actor or role-playing, and never describe actions or emotions in brackets.

Who you are: {style}

Your real background (this is the truth, even where your resume says otherwise): {truth}

Your resume says: {resume}

How to answer:
- Reply to what the interviewer just said, in first person, conversational spoken English, no lists or markdown.
- Keep every number from your real background exactly as written (never round, shrink or change them).
- Typical length {min_words}-{max_words} words for a substantive answer; shorter for small talk.
- If the interviewer asks you to wait, repeat or clarify, react naturally.
- If the interviewer invites your questions near the end: {end_question}
- If the interviewer is closing the interview, just thank them briefly."""

PERSONA_USER = """\
Conversation so far (oldest first):
{conversation}

The interviewer just said: "{question}"
{instruction}Your reply (the words you say, nothing else):"""


def resume_digest(profile: dict[str, Any]) -> str:
    parts: list[str] = []
    if profile.get("headline"):
        parts.append(str(profile["headline"]))
    for role in (profile.get("roles") or [])[:3]:
        line = f"{role.get('title')} at {role.get('company')}"
        achievements = [a.get("text") for a in role.get("achievements") or [] if isinstance(a, dict)]
        if achievements:
            line += ": " + " ".join(str(a) for a in achievements[:4])
        parts.append(line)
    return " | ".join(parts)


def judge_resume_digest(profile: dict[str, Any]) -> str:
    """Resume summary for the judge: roles plus every claim the interviewer may cite."""
    claims = [
        f"{c.get('id')}: {c.get('claim')}"
        for c in profile.get("claims_to_verify") or []
        if isinstance(c, dict)
    ]
    text = resume_digest(profile)
    if claims:
        text += "\nResume claims: " + " | ".join(claims)
    return text


_STAGE = re.compile(r"\s*[\[(\*][^\])\*]{0,80}[\])\*]\s*")
_PREFIX = re.compile(r"^\s*(?:candidate|me|you|answer|reply)\s*:\s*", re.IGNORECASE)


def clean_answer(text: str, *, echo: str | None = None) -> str:
    text = _PREFIX.sub("", text.strip())
    if echo and text.lower().startswith(echo.strip().lower()[:60]):
        text = text[len(echo.strip()) :].strip()  # the role-play model sometimes echoes the question
    text = _STAGE.sub(" ", text)
    text = text.strip().strip('"').strip("“”").strip()
    return re.sub(r"\s+", " ", text)


@dataclass(slots=True)
class Exchange:
    speaker: str  # interviewer | candidate
    text: str


class PersonaResponder:
    """Generates the persona's reply to the interviewer's last utterance."""

    def __init__(self, ai: Any, persona: Persona, *, job_title: str) -> None:
        self.ai = ai
        self.persona = persona
        self.job_title = job_title
        self.profile = persona.profile_doc()
        self.calls = 0

    def system_prompt(self) -> str:
        p = self.persona
        end = (
            f'ask exactly this question: "{p.end_question}"'
            if p.end_question
            else "say you have no further questions and thank them."
        )
        return PERSONA_SYSTEM.format(
            job_title=self.job_title,
            style=p.style,
            truth=p.truth,
            resume=resume_digest(self.profile),
            min_words=p.words[0],
            max_words=p.words[1],
            end_question=end,
        )

    async def reply(
        self, history: list[Exchange], question: str, *, turn_index: int, hint: str | None = None
    ) -> tuple[str, str]:
        """(text, move kind) for the candidate's next turn."""
        from app.ai.base import CallContext
        from app.domain.enums import ModelTask

        move = self.persona.moves.get(turn_index)
        if move is not None and move.text:
            return move.text, move.kind
        conversation = "\n".join(
            f"{'Interviewer' if e.speaker == 'interviewer' else 'You'}: {e.text}" for e in history[-12:]
        )
        instruction = f"Instruction for this turn: {move.instruction}\n" if move and move.instruction else ""
        if hint and not instruction:
            instruction = f"Note: {hint}\n"
        messages = [
            {"role": "system", "content": self.system_prompt()},
            {
                "role": "user",
                "content": PERSONA_USER.format(
                    conversation=conversation or "(the interview just started)",
                    question=question,
                    instruction=instruction,
                ),
            },
        ]
        self.calls += 1
        result = await self.ai.llm.chat(
            messages,
            context=CallContext(task=ModelTask.QUESTION_GENERATION, prompt_version="quality.persona"),
            endpoint="main",
            temperature=0.7,
            max_tokens=320,
            timeout=60.0,
        )
        text = clean_answer(result.text, echo=question)
        if self.persona.asr_noise:
            text = apply_asr_noise(text)
        if move is not None and move.suffix:
            text = f"{text.rstrip()}{move.suffix}"
        return text or "Sorry, could you repeat that?", (move.kind if move else "answer")


