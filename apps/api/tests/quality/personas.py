# ---------------------------------------------------------------- personas


@dataclass(frozen=True, slots=True)
class Move:
    """A scripted candidate move at one turn index.

    ``kind`` names the behaviour the checks expect (clarify, think,
    dont_know, candidate_question, inject, contradict). ``text`` is said
    verbatim; otherwise ``instruction`` steers the generated answer.
    """

    kind: str
    text: str | None = None
    instruction: str | None = None
    suffix: str | None = None  # appended verbatim to a generated answer (injections)


@dataclass(frozen=True, slots=True)
class Persona:
    key: str
    label: str
    candidate_name: str
    profile: str  # senior | mid | junior
    style: str
    truth: str
    words: tuple[int, int]
    moves: dict[int, Move] = field(default_factory=dict)
    rank: int | None = None  # expected scoring order (1 = best) for the sanity check
    end_question: str | None = None  # asked when the interviewer invites questions
    tags: frozenset[str] = frozenset()
    # Deep evaluation is skipped where no check depends on scores (saves shared model time).
    evaluate: bool = True
    asr_noise: bool = False  # pass generated answers through speech-recognition style substitutions

    def profile_doc(self) -> dict[str, Any]:
        builder = PROFILE_BUILDERS[self.profile]
        return builder(self.candidate_name)


