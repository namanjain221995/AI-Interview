"""Scripted candidate personas for the interview-quality harness.

Each persona answers by text, conditioned on the question the interviewer
actually asked. Answers are generated by the main model from a role-play
prompt (``PersonaResponder``); some turns are *scripted moves* (clarifying
question, "let me think", "I don't know", a question about the role, a prompt
injection, ...) so the checks know exactly which behaviour to expect at which
point. Fixed-text moves exercise the deterministic special-turn heuristics;
instruction moves exercise the model path with natural variation.

Profiles: the senior personas use the real Jane Doe profile produced by the
resume pipeline (``fixtures/jane_doe_profile.json``); the mid-level and junior
personas get derived profiles with matching (smaller) claims, so the resume
and the persona's real experience agree except where a persona is *meant* to
contradict it.
"""

