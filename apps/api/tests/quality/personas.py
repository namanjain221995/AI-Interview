# Typical misrecognitions of technical terms by a general-purpose speech recognizer.
ASR_SUBSTITUTIONS = (
    (re.compile(r"\bKarpenter\b"), "Carpenter"),
    (re.compile(r"\bPrometheus\b"), "Ometheus"),
    (re.compile(r"\bkubectl\b", re.I), "cube control"),
    (re.compile(r"\bTerraform\b"), "terra form"),
    (re.compile(r"\bEKS\b"), "E K S"),
    (re.compile(r"\bPodDisruptionBudgets?\b"), "pod disruption budget"),
    (re.compile(r"\bArgo Rollouts\b"), "Argo roll outs"),
    (re.compile(r"\bGrafana\b"), "Graphana"),
    (re.compile(r"\bHPA\b"), "H P A"),
    (re.compile(r"\bIRSA\b"), "Ursa"),
)


def apply_asr_noise(text: str) -> str:
    for pattern, replacement in ASR_SUBSTITUTIONS:
        text = pattern.sub(replacement, text)
    return text


