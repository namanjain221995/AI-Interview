"""Introduction utterance: name, role, round, how it works, that the
candidate can ask to repeat or take time, and a monitoring reminder when
monitoring is enabled. Generated by the main model during
``session.prepare`` (validated) with a natural template fallback."""

from __future__ import annotations

import hashlib
import re

from pydantic import BaseModel, ConfigDict, Field

from app.ai.base import AIError, AIServices, CallContext
from app.ai.registry import get_ai
from app.core.logging import get_logger
from app.domain.enums import ModelTask, SegmentKind
from app.services.interview.prompts import OPENING
from app.services.interview.state import InterviewState

log = get_logger(__name__)

MAX_OPENING_WORDS = 60  # ~12-20 s of speech
MIN_OPENING_WORDS = 15


class SpokenText(BaseModel):
    model_config = ConfigDict(extra="forbid")

    speech: str = Field(..., min_length=1, max_length=900)


_SEGMENT_PHRASES = {
    SegmentKind.RESUME_VALIDATION: "your recent experience",
    SegmentKind.TECHNICAL: "a few technical scenarios",
    SegmentKind.SYSTEM_DESIGN: "a system design discussion",
    SegmentKind.BEHAVIORAL: "how you work with others",
    SegmentKind.LEADERSHIP: "your leadership experience",
    SegmentKind.PROBLEM_SOLVING: "some problem solving",
    SegmentKind.RECRUITER: "what you're looking for next",
    SegmentKind.CODING: "a short coding exercise",
}


def _pick(options: list[str], seed: str) -> str:
    idx = int(hashlib.sha1(seed.encode()).hexdigest(), 16) % len(options)  # noqa: S324 - variation only
    return options[idx]


def coverage_phrase(state: InterviewState) -> str:
    """One short phrase for the format ("your recent experience, a few
    technical scenarios and a short coding exercise")."""
    parts: list[str] = []
    kinds = [s.kind for s in state.plan.segments] if state.plan else []
    if state.round_config.coding.enabled and SegmentKind.CODING not in kinds:
        kinds.append(SegmentKind.CODING)
    for kind in kinds:
        phrase = _SEGMENT_PHRASES.get(kind)
        if phrase and phrase not in parts:
            parts.append(phrase)
    parts = parts[:3] or ["your experience and a few scenarios related to the role"]
    if len(parts) == 1:
        return parts[0]
    return ", ".join(parts[:-1]) + " and " + parts[-1]


def template_opening(state: InterviewState) -> str:
    """~12-20 s of speech: greeting + who/what, the format in one line, and
    that they can ask to repeat. The first question follows separately;
    monitoring information lives in the UI."""
    first = state.candidate_first_name
    job = (state.job_summary or {}).get("title") or "this"
    greet = f"Hi {first}, I'm {state.interviewer_name}," if first else f"Hi, I'm {state.interviewer_name},"
    sentences = [
        f"{greet} the AI interviewer for the {job} role.",
        f"Over about {state.round_config.duration_minutes} minutes we'll cover {coverage_phrase(state)}.",
        _pick(
            [
                "Feel free to ask me to repeat or clarify anything, anytime.",
                "You can ask me to repeat or rephrase a question at any point.",
            ],
            state.session_id,
        ),
    ]
    return " ".join(sentences)


def validate_opening(text: str, state: InterviewState) -> list[str]:
    problems: list[str] = []
    words = text.split()
    if len(words) > MAX_OPENING_WORDS:
        problems.append("too_long")
    if len(words) < MIN_OPENING_WORDS:
        problems.append("too_short")
    if state.interviewer_name.lower() not in text.lower():
        problems.append("missing_interviewer_name")
    if re.search(r"[*#`]|\n\s*[-\d]", text):
        problems.append("markdown")
    if "?" in text:
        problems.append("contains_question")
    if any(w in text.lower() for w in ("monitor", "policy", "recorded")):
        problems.append("monitoring_script")
    lowered = text.lower()
    if not any(w in lowered for w in ("repeat", "clarif", "rephrase")):
        problems.append("missing_repeat_hint")
    return problems


async def generate_opening(
    state: InterviewState, *, ai: AIServices | None = None, timeout_s: float = 15.0
) -> tuple[str, str]:
    """(text, source) with source ``model`` or ``template``."""
    services = ai or get_ai()
    job = state.job_summary or {}
    prompt = OPENING.render(
        interviewer_name=state.interviewer_name,
        first_name=state.candidate_first_name,
        job_title=job.get("title") or "the role",
        company=job.get("company"),
        round_name=state.round_config.name,
        duration_minutes=state.round_config.duration_minutes,
        coverage=coverage_phrase(state),
    )
    try:
        result = await services.llm.structured(
            SpokenText,
            [{"role": "user", "content": prompt}],
            context=CallContext(
                task=ModelTask.OPENING,
                session_id=state.session_id,
                organization_id=state.organization_id,
                prompt_version=OPENING.version,
            ),
            temperature=0.6,
            max_tokens=400,
            timeout=timeout_s,
            max_attempts=2,
        )
    except AIError as exc:
        log.info("engine.opening_template", session_id=state.session_id, reason=type(exc).__name__)
        return template_opening(state), "template"
    text = re.sub(r"\s+", " ", result.value.speech).strip()
    problems = validate_opening(text, state)
    if problems:
        log.info("engine.opening_rejected", session_id=state.session_id, problems=problems)
        return template_opening(state), "template"
    return text, "model"


__all__ = ["SpokenText", "coverage_phrase", "generate_opening", "template_opening", "validate_opening"]
